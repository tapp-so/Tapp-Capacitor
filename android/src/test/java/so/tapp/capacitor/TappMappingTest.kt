package so.tapp.capacitor

import com.example.tapp.services.network.RequestModels
import org.json.JSONObject
import org.junit.Assert.*
import org.junit.Test

class TappMappingTest {
    @Test
    fun mapsEveryStandardEventInContractOrder() {
        val names = listOf(
            "add_payment_info", "add_to_cart", "add_to_wishlist", "complete_registration",
            "contact", "customize_product", "donate", "find_location", "initiate_checkout",
            "generate_lead", "purchase", "schedule", "search", "start_trial", "submit_application",
            "subscribe", "view_content", "click_button", "download_file", "join_group",
            "achieve_level", "create_group", "create_role", "link_click", "link_impression",
            "apply_for_loan", "loan_approval", "loan_disbursal", "login", "rate", "spend_credits",
            "unlock_achievement", "add_shipping_info", "earn_virtual_currency", "start_level",
            "complete_level", "post_score", "select_content", "begin_tutorial", "complete_tutorial"
        )
        names.forEachIndexed { index, name ->
            val action = TappMapping.eventAction(index + 1)!!
            assertEquals(index + 1, action.rawValue)
            assertEquals("tapp_$name", action.javaClass.simpleName)
            assertFalse(action.isCustom)
            assertEquals(action, TappMapping.eventAction((index + 1).toDouble()))
        }
    }

    @Test
    fun customEventsUseProvidedNameOrDefault() {
        assertEquals(RequestModels.EventAction.custom("checkout"), TappMapping.eventAction(0, "checkout"))
        assertEquals(
            RequestModels.EventAction.custom("custom_event_autogenerated"),
            TappMapping.eventAction(0)
        )
        assertEquals(RequestModels.EventAction.custom(""), TappMapping.eventAction(0, ""))
    }

    @Test
    fun rejectsInvalidActionsWithoutCoercingOrTruncating() {
        listOf(null, JSONObject.NULL, "1", true, -1, 41, 1.5, Double.NaN,
            Double.POSITIVE_INFINITY, Double.NEGATIVE_INFINITY, Long.MAX_VALUE).forEach {
            assertNull("Unexpected action for $it", TappMapping.eventAction(it))
        }
    }

    @Test
    fun metadataKeepsOnlyFlatJsonScalars() {
        val input = linkedMapOf(
            "text" to "value", "empty" to "", "flag" to false, "int" to 3,
            "long" to 4L, "double" to 2.5, "zero" to 0,
            "null" to null, "jsonNull" to JSONObject.NULL, "object" to JSONObject(),
            "map" to mapOf("key" to "value"), "list" to listOf(1),
            "nan" to Double.NaN, "infinity" to Double.POSITIVE_INFINITY,
            "negativeInfinity" to Float.NEGATIVE_INFINITY
        )
        val expected = mapOf("text" to "value", "empty" to "", "flag" to false,
            "int" to 3, "long" to 4L, "double" to 2.5, "zero" to 0)
        assertEquals(expected, TappMapping.metadata(input))
        assertEquals(expected.keys, JSONObject(TappMapping.metadata(input)!!).keys().asSequence().toSet())
        assertTrue(input.containsKey("nan"))
        assertNull(TappMapping.metadata(null))
        assertEquals(emptyMap<String, Any>(), TappMapping.metadata(emptyMap<String, Any>()))
    }

    @Test
    fun urlDataDropsNonStringsWithoutCoercion() {
        assertEquals(mapOf("name" to "value", "empty" to ""), TappMapping.stringData(mapOf(
            "name" to "value", "empty" to "", "int" to 1, "flag" to true,
            "null" to JSONObject.NULL, "nested" to mapOf("a" to "b")
        )))
        assertEquals(emptyMap<String, String>(), TappMapping.stringData(null))
    }

    @Test
    fun removesNativePlaceholdersFromOptionalFields() {
        listOf(null, "", "  ", "null", " NULL ", "-1", "tapp_url was not returned",
            "attr_tapp_url was not returned", "influencer was not returned",
            "deepLink was not returned").forEach { assertNull(TappMapping.optionalString(it)) }
        assertEquals("https://example.com/null", TappMapping.optionalString("https://example.com/null"))
        assertEquals("someone was not returned", TappMapping.optionalString("someone was not returned"))
    }

    @Test
    fun successfulLinkDataMatchesJsShape() {
        val response = response().copy(
            tappUrl = "https://example.com/t", attrTappUrl = "https://example.com/a",
            influencer = "person", data = mapOf("key" to "value"),
            isFirstSession = true, deepLink = "app://product"
        )
        assertEquals(mapOf(
            "error" to false, "tappUrl" to "https://example.com/t", "attrTappUrl" to "https://example.com/a",
            "influencer" to "person", "data" to mapOf("key" to "value"),
            "isFirstSession" to true, "deepLink" to "app://product"
        ), TappMapping.linkData(response))
    }

    @Test
    fun unavailableOptionalLinkFieldsAreOmitted() {
        assertEquals(mapOf("error" to false), TappMapping.linkData(response()))
        assertEquals(mapOf("error" to false, "isFirstSession" to false, "data" to emptyMap<String, String>()),
            TappMapping.linkData(response().copy(
                tappUrl = "tapp_url was not returned", attrTappUrl = "attr_tapp_url was not returned",
                influencer = "influencer was not returned", deepLink = "deepLink was not returned",
                isFirstSession = false, data = emptyMap()
            )))
    }

    @Test
    fun preservesCustomDataStringsIncludingLiteralNull() {
        val data = mapOf("value" to "null", "empty" to "", "id" to "-1")
        assertEquals(data, TappMapping.linkData(response().copy(data = data))["data"])
    }

    @Test
    fun failuresContainOnlyErrorAndMessage() {
        assertEquals(mapOf("error" to true, "message" to "backend failure"),
            TappMapping.linkData(response().copy(error = true, message = "backend failure", tappUrl = "ignored")))
        assertEquals(mapOf("error" to true, "message" to "No link data returned"), TappMapping.linkData(null))
        assertEquals(mapOf("error" to true, "message" to "An unexpected error occurred"),
            TappMapping.linkData(response().copy(error = true, message = null)))
        assertEquals(mapOf("error" to true, "message" to "Tapp has not been started. Call start() first."),
            TappMapping.error(TappMapping.NOT_STARTED))
    }

    private fun response() = RequestModels.TappLinkDataResponse(
        error = false, message = "Ok", tappUrl = null, attrTappUrl = null,
        influencer = null, data = null, isFirstSession = null, deepLink = null
    )
}
