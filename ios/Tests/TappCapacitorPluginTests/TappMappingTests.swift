import XCTest
import CoreFoundation
@testable import TappCapacitorPlugin

final class TappMappingTests: XCTestCase {
    func testEveryStandardEventMatchesRN() {
        let names = [
            "add_payment_info", "add_to_cart", "add_to_wishlist", "complete_registration",
            "contact", "customize_product", "donate", "find_location", "initiate_checkout",
            "generate_lead", "purchase", "schedule", "search", "start_trial",
            "submit_application", "subscribe", "view_content", "click_button", "download_file",
            "join_group", "achieve_level", "create_group", "create_role", "link_click",
            "link_impression", "apply_for_loan", "loan_approval", "loan_disbursal", "login",
            "rate", "spend_credits", "unlock_achievement", "add_shipping_info",
            "earn_virtual_currency", "start_level", "complete_level", "post_score",
            "select_content", "begin_tutorial", "complete_tutorial"
        ]
        XCTAssertEqual(names.count, 40)
        for (index, name) in names.enumerated() {
            XCTAssertEqual(TappMapping.eventName(action: index + 1, customValue: nil), "tapp_" + name)
        }
    }

    func testCustomEventAndInvalidActions() {
        XCTAssertEqual(TappMapping.eventName(action: 0, customValue: "my_event"), "my_event")
        XCTAssertEqual(TappMapping.eventName(action: 0, customValue: nil), "custom_event_autogenerated")
        XCTAssertEqual(TappMapping.eventName(action: 0, customValue: ""), "custom_event_autogenerated")
        XCTAssertEqual(TappMapping.eventName(action: 0, customValue: "   "), "custom_event_autogenerated")
        XCTAssertEqual(TappMapping.eventName(action: 0, customValue: " my_event "), " my_event ")
        XCTAssertEqual(TappMapping.eventName(action: 1.0, customValue: "ignored"), "tapp_add_payment_info")
        let invalid: [Any] = [-1, 41, 1.5, Double.nan, Double.infinity, -Double.infinity,
                              true, false, NSNumber(value: true), "1", NSNull(), [1]]
        for value in invalid {
            XCTAssertNil(TappMapping.eventName(action: value, customValue: nil), "Unexpected valid action: \(value)")
        }
        XCTAssertNil(TappMapping.eventName(action: nil, customValue: nil))
    }

    func testMetadataPreservesBooleanAndNumericTypesAndDropsUnsupportedValues() throws {
        let input: [String: Any] = [
            "text": "hello", "yes": true, "no": NSNumber(value: false),
            "zero": NSNumber(value: 0), "one": NSNumber(value: 1), "fraction": 1.25,
            "negative": -4, "nan": Double.nan, "positiveInfinity": Double.infinity,
            "negativeInfinity": -Double.infinity, "null": NSNull(), "array": [1, 2],
            "object": ["nested": "value"], "date": Date(timeIntervalSince1970: 0)
        ]
        let result = try XCTUnwrap(TappMapping.metadata(input))
        XCTAssertEqual(Set(result.keys), Set(["text", "yes", "no", "zero", "one", "fraction", "negative"]))
        XCTAssertEqual(result["text"] as? String, "hello")
        XCTAssertTrue(result["yes"] is Bool)
        XCTAssertTrue(result["no"] is Bool)
        XCTAssertEqual(result["yes"] as? Bool, true)
        XCTAssertEqual(result["no"] as? Bool, false)
        XCTAssertTrue(result["one"] is Double)
        XCTAssertEqual(result["zero"] as? Double, 0)
        XCTAssertEqual(result["one"] as? Double, 1)
        XCTAssertEqual(result["fraction"] as? Double, 1.25)
        XCTAssertEqual(result["negative"] as? Double, -4)
        XCTAssertNil(TappMapping.metadata(nil))
        XCTAssertEqual(TappMapping.metadata([:])?.count, 0)
    }

    func testStringDataDropsNonStrings() {
        XCTAssertEqual(TappMapping.stringData([
            "keep": "value", "empty": "", "number": 1, "bool": true,
            "null": NSNull(), "array": ["x"], "object": ["x": "y"]
        ]), ["keep": "value", "empty": ""])
        XCTAssertNil(TappMapping.stringData(nil))
        XCTAssertEqual(TappMapping.stringData([:]), [:])
    }

    func testLinkDictionaryUsesContractKeysAndIsJSONSafe() throws {
        let result = TappMapping.linkData(
            tappURL: URL(string: "https://example.com/link"),
            attributedTappURL: URL(string: "https://example.com/attribution"),
            influencer: "creator", data: ["campaign": "launch"], isFirstSession: true
        )
        XCTAssertEqual(Set(result.keys), Set(["error", "tappUrl", "attrTappUrl", "influencer", "data", "isFirstSession"]))
        XCTAssertEqual(result["error"] as? Bool, false)
        XCTAssertEqual(result["tappUrl"] as? String, "https://example.com/link")
        XCTAssertEqual(result["attrTappUrl"] as? String, "https://example.com/attribution")
        XCTAssertEqual(result["influencer"] as? String, "creator")
        XCTAssertEqual(result["data"] as? [String: String], ["campaign": "launch"])
        XCTAssertEqual(result["isFirstSession"] as? Bool, true)
        XCTAssertNoThrow(try JSONSerialization.data(withJSONObject: result))
    }

    func testLinkDictionaryOmitsMissingFieldsAndPreservesFalseAndEmptyData() {
        let empty = TappMapping.linkData(
            tappURL: nil, attributedTappURL: nil, influencer: nil, data: nil, isFirstSession: nil
        )
        XCTAssertEqual(Set(empty.keys), ["error"])
        XCTAssertEqual(empty["error"] as? Bool, false)
        let result = TappMapping.linkData(
            tappURL: nil, attributedTappURL: nil, influencer: nil, data: [:], isFirstSession: false
        )
        XCTAssertEqual(result["data"] as? [String: String], [:])
        XCTAssertEqual(result["isFirstSession"] as? Bool, false)
    }

    func testFailureContainsOnlyErrorAndMessage() {
        let result = TappMapping.failure(message: "Link unavailable")
        XCTAssertEqual(Set(result.keys), Set(["error", "message"]))
        XCTAssertEqual(result["error"] as? Bool, true)
        XCTAssertEqual(result["message"] as? String, "Link unavailable")
        XCTAssertTrue(JSONSerialization.isValidJSONObject(result))
    }

    func testURLValidationRejectsMalformedAndDisallowedURLs() {
        let invalid: [String?] = [
            nil, "", "   ", " \n\t", "no-scheme/path",
            "https://[invalid", "http://exa mple.com",
            "javascript:alert(1)", "JavaScript:alert(1)",
            "data:text/plain,x", "DATA:text/plain,x",
            "file:///etc/hosts", "FILE:///etc/hosts"
        ]
        for value in invalid {
            XCTAssertNil(TappMapping.parsedURL(value), "Unexpected valid URL: \(String(describing: value))")
        }
    }

    func testURLValidationReturnsTrimmedURLs() {
        let valid = [
            ("https://example.com/path", "https://example.com/path"),
            ("http://example.com", "http://example.com"),
            ("myapp://x", "myapp://x"),
            ("  https://example.com/a  ", "https://example.com/a")
        ]
        for (value, expected) in valid {
            XCTAssertEqual(TappMapping.parsedURL(value)?.absoluteString, expected)
        }
    }
}
